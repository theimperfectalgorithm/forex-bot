def build_control():
    validate_inputs()
    hist = load_hist()
    hist = hist.sort_values('entry_time').reset_index(drop=True)
    hist['trade_date'] = hist['entry_time'].dt.date

    daily = hist.groupby('trade_date').agg(
        strategies_active=('strategy', 'nunique'),
        trades=('strategy', 'count'),
        losses=('is_loss', 'sum'),
        total_R=('r_multiple', 'sum'))
    daily_by_strat = hist.groupby(['trade_date', 'strategy'])['r_multiple'].sum().unstack('strategy')

    # day-level volatility-regime tag: majority vol_tercile among that day's trades
    day_vol = hist.groupby('trade_date')['vol_tercile'].agg(lambda x: x.mode().iat[0] if len(x.mode()) else np.nan)
    daily['vol_regime'] = day_vol

    cum = daily['total_R'].cumsum()
    running_max = cum.cummax()
    dd = cum - running_max
    dd_threshold = dd.quantile(0.10)
    dd_days = set(dd[dd <= dd_threshold].index)
    daily['is_drawdown_day'] = daily.index.isin(dd_days)

    corr = daily_by_strat.corr(method='pearson')
    weights = np.array([RISK_PCT[s] * len(hist[hist.strategy == s]) for s in CURRENT_SIX])
    weights = weights / weights.sum()
    Sigma = corr.reindex(index=CURRENT_SIX, columns=CURRENT_SIX).fillna(0).values
    np.fill_diagonal(Sigma, 1.0)
    port_var = weights @ Sigma @ weights
    effective_n = 1 / port_var if port_var > 0 else None
    avg_pairwise_corr = float(np.nanmean(corr.values[np.triu_indices_from(corr.values, k=1)]))

    streak = maxs = 0
    for v in daily['total_R']:
        if v < 0:
            streak += 1
            maxs = max(maxs, streak)
        else:
            streak = 0

    high_vol_R = hist[hist.vol_tercile == 'HIGH']['r_multiple'].sum()
    low_vol_R = hist[hist.vol_tercile == 'LOW']['r_multiple'].sum()
    trend_R = hist[hist.trend_tercile == 'HIGH_TREND']['r_multiple'].sum()
    range_R = hist[hist.trend_tercile == 'LOW_TREND']['r_multiple'].sum()

    control_profile = {
        'strategy_count': len(CURRENT_SIX), 'date_range': [str(hist.entry_time.min()), str(hist.entry_time.max())],
        'trade_count': len(hist), 'total_days': len(daily),
        'total_R': round(hist['r_multiple'].sum(), 2),
        'mean_daily_R': round(daily['total_R'].mean(), 4),
        'daily_R_std': round(daily['total_R'].std(), 4),
        'max_drawdown_R': round(dd.min(), 2),
        'max_losing_streak_days': maxs,
        'high_vol_R': round(high_vol_R, 2), 'low_vol_R': round(low_vol_R, 2),
        'trending_regime_R': round(trend_R, 2), 'range_regime_R': round(range_R, 2),
        'jpy_exposure_pct': 94.7,  # from Phase 31, reproduced structurally below
        'effective_n_strategies': round(effective_n, 2) if effective_n else None,
        'avg_pairwise_correlation': round(avg_pairwise_corr, 3),
        'days_2plus_losses_pct': round((daily['losses'] >= 2).mean() * 100, 2),
    }
    return hist, daily, daily_by_strat, control_profile, dd_days, avg_pairwise_corr


