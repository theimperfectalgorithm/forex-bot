# Empirical calibration anchors (Part 7) -- derived from the control's own
# per-strategy daily R, NOT invented. Printed and used, not silently assumed.


def empirical_calibration(hist, daily_by_strat):
    per_strat_daily_std = daily_by_strat.std()
    calib = {
        'per_strategy_daily_R_std_range': [round(per_strat_daily_std.min(), 3), round(per_strat_daily_std.max(), 3)],
        'per_strategy_daily_R_std_median': round(per_strat_daily_std.median(), 3),
        'trade_freq_per_week_range': [round(len(hist[hist.strategy == s]) / (774 / 5), 2) for s in CURRENT_SIX],
    }
    print(f"[calibration] {json.dumps(calib, indent=2)}")
    return calib


def simulate_series_raw(control_r, is_dd, is_high_vol, rho_normal, rho_dd, tilt, p_trade, sigma_arch, rng):
    """Core synthetic generator, parameterized directly (no archetype
    lookup) so it can be reused identically across archetype/ablation/
    currency/mechanism scenarios. One call = one random draw."""
    n = len(control_r)
    control_z = (control_r - control_r.mean()) / (control_r.std() + 1e-9)
    noise = rng.standard_normal(n)
    rho = np.where(is_dd, rho_dd, rho_normal)
    arch_r = (rho * control_z + np.sqrt(np.clip(1 - rho ** 2, 0, 1)) * noise) * sigma_arch
    arch_r = arch_r + np.where(is_high_vol, tilt, 0.0)
    trades_mask = rng.random(n) < p_trade
    return np.where(trades_mask, arch_r, 0.0)


def simulate_archetype_daily_series(archetype_key, daily, dd_days, control_std_anchor, weight_mult=1.0, n_days=None, rng=None):
    """SYNTHETIC. Single draw for one archetype -- kept for backward-compat
    call sites; repeated_scenario_metrics() below is used wherever a stable
    (non-noise-driven) result is required."""
    arch = ARCHETYPES[archetype_key]
    n = len(daily) if n_days is None else n_days
    control_r = daily['total_R'].values[:n]
    is_dd = daily['is_drawdown_day'].values[:n]
    is_high_vol = (daily['vol_regime'].values[:n] == 'HIGH')
    return simulate_series_raw(
        control_r, is_dd, is_high_vol,
        CORR_BAND_POINTS[arch['normal_corr_band']], DD_CORR_LEVEL[arch['dd_corr_band']],
        HIGHVOL_TILT[arch['high_vol_behavior']] * weight_mult, min(1.0, arch['trade_freq_per_week'] / 5.0),
        control_std_anchor * weight_mult, rng or RNG)


N_REPS = 300  # replications averaged per scenario, per the instruction not to
              # select/report a single noisy draw as if it were a stable result


def repeated_scenario_metrics(control_r, is_dd, is_high_vol, rho_normal, rho_dd, tilt, p_trade, sigma_arch,
                               n_reps=N_REPS, seed0=20260815):
    """Runs n_reps independent draws of the same scenario and returns the
    MEAN and STD across draws for every metric -- this is what actually
    answers 'is this result robust or is it noise', per the anti-optimization
    rule (Part 24: 'if a result depends heavily on a particular synthetic
    assumption: REPORT IT AS SENSITIVE'). std_total_R / std_max_dd etc. are
    the sensitivity signal."""
    rows = []
    corr_normal_list, corr_dd_list = [], []
    for i in range(n_reps):
        rng = np.random.default_rng(seed0 + i)
        arch_r = simulate_series_raw(control_r, is_dd, is_high_vol, rho_normal, rho_dd, tilt, p_trade, sigma_arch, rng)
        combined = control_r + arch_r
        m = portfolio_metrics_from_series(combined, is_dd, is_high_vol)
        rows.append(m)
        if is_dd.sum() > 5 and (~is_dd).sum() > 5 and arch_r[is_dd].std() > 0 and arch_r[~is_dd].std() > 0:
            corr_normal_list.append(np.corrcoef(control_r[~is_dd], arch_r[~is_dd])[0, 1])
            corr_dd_list.append(np.corrcoef(control_r[is_dd], arch_r[is_dd])[0, 1])
    df = pd.DataFrame(rows)
    numeric_cols = [c for c in df.columns if c != 'label']
    mean_row = df[numeric_cols].mean()
    std_row = df[numeric_cols].std()
    out = {f'{c}_mean': round(mean_row[c], 3) for c in numeric_cols}
    out.update({f'{c}_std': round(std_row[c], 3) for c in numeric_cols})
    out['realized_normal_corr_mean'] = round(np.mean(corr_normal_list), 3) if corr_normal_list else None
    out['realized_drawdown_corr_mean'] = round(np.mean(corr_dd_list), 3) if corr_dd_list else None
    out['n_reps'] = n_reps
    return out


