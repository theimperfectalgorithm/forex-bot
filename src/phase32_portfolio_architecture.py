def portfolio_metrics_from_series(r_series, dd_days_mask, vol_mask_high, label=''):
    r_series = np.asarray(r_series)
    total_R = r_series.sum()
    mean_daily = r_series.mean()
    std_daily = r_series.std()
    cum = np.cumsum(r_series)
    running_max = np.maximum.accumulate(cum)
    dd = cum - running_max
    max_dd = dd.min()
    # drawdown duration: longest run where dd < 0
    in_dd = dd < -1e-9
    max_dd_duration = 0
    cur = 0
    for v in in_dd:
        if v:
            cur += 1
            max_dd_duration = max(max_dd_duration, cur)
        else:
            cur = 0
    streak = maxs = 0
    for v in r_series:
        if v < 0:
            streak += 1
            maxs = max(maxs, streak)
        else:
            streak = 0
    high_vol_R = r_series[vol_mask_high].sum() if vol_mask_high.any() else np.nan
    low_vol_R = r_series[~vol_mask_high].sum()
    worst_5pct = np.percentile(r_series, 5)
    worst_1pct = np.percentile(r_series, 1)
    return {
        'label': label, 'total_R': round(total_R, 2), 'mean_daily_R': round(mean_daily, 4),
        'daily_vol': round(std_daily, 4), 'max_drawdown': round(max_dd, 2),
        'max_drawdown_duration_days': int(max_dd_duration), 'max_losing_streak_days': int(maxs),
        'high_vol_R': round(high_vol_R, 2) if high_vol_R == high_vol_R else None,
        'low_vol_R': round(low_vol_R, 2),
        'worst_5pct_day': round(worst_5pct, 3), 'worst_1pct_day': round(worst_1pct, 3),
    }


def monte_carlo_block_bootstrap(r_series, n_sims=N_MC, block=5):
    """Block bootstrap (preserves local autocorrelation/regime clustering,
    per the instruction not to shuffle in a way that destroys regime
    structure) of the given daily series. Returns arrays of simulated
    total_R, max_drawdown, max_losing_streak."""
    n = len(r_series)
    n_blocks = int(np.ceil(n / block))
    totals, dds, streaks = [], [], []
    for _ in range(n_sims):
        idx = RNG.integers(0, n - block, size=n_blocks)
        sim = np.concatenate([r_series[i:i + block] for i in idx])[:n]
        cum = np.cumsum(sim)
        dd = cum - np.maximum.accumulate(cum)
        s = ms = 0
        for v in sim:
            if v < 0:
                s += 1
                ms = max(ms, s)
            else:
                s = 0
        totals.append(sim.sum())
        dds.append(dd.min())
        streaks.append(ms)
    return np.array(totals), np.array(dds), np.array(streaks)


